"""Typed contracts used to pass work between the specialized agents."""

from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class RequirementInput(BaseModel):
    """Natural-language requirement submitted to the Requirement Agent."""

    model_config = ConfigDict(extra="forbid")

    requirement: str = Field(min_length=1, max_length=10_000)

    @field_validator("requirement")
    @classmethod
    def requirement_must_not_be_blank(cls, value: str) -> str:
        normalized = " ".join(value.split())
        if not normalized:
            raise ValueError("Requirement must not be blank.")
        return normalized


# Kept as an alias so the existing API and workflow imports remain compatible.
RequirementRequest = RequirementInput


class PlannedFile(BaseModel):
    """A file the Code Agent is expected to create or update."""

    model_config = ConfigDict(extra="forbid")

    path: str = Field(min_length=1)
    action: Literal["create", "modify"]
    purpose: str = Field(min_length=1)


class DevelopmentPlan(BaseModel):
    """Deterministic Requirement Agent output; contains no source code."""

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(min_length=1)
    assumptions: list[str] = Field(default_factory=list)
    technologies: list[str] = Field(default_factory=list)
    files_to_create: list[str] = Field(default_factory=list)
    files_to_modify: list[str] = Field(default_factory=list)
    implementation_steps: list[str] = Field(default_factory=list)
    testing_requirements: list[str] = Field(default_factory=list)

    @model_validator(mode="before")
    @classmethod
    def migrate_legacy_plan_fields(cls, value: Any) -> Any:
        """Accept the original foundation plan shape without exposing it in JSON."""
        if not isinstance(value, dict) or not (
            "files" in value or "acceptance_criteria" in value
        ):
            return value

        migrated = dict(value)
        legacy_files = migrated.pop("files", [])
        migrated.pop("acceptance_criteria", None)
        for item in legacy_files:
            planned_file = (
                item if isinstance(item, PlannedFile) else PlannedFile.model_validate(item)
            )
            field_name = (
                "files_to_create" if planned_file.action == "create" else "files_to_modify"
            )
            migrated.setdefault(field_name, []).append(planned_file.path)
        return migrated

    @property
    def files(self) -> list[PlannedFile]:
        """Expose the prior Code Agent contract while retaining the new JSON shape."""
        return [
            PlannedFile(path=path, action=action, purpose="Planned implementation file")
            for action, paths in (
                ("create", self.files_to_create),
                ("modify", self.files_to_modify),
            )
            for path in paths
        ]

    @property
    def acceptance_criteria(self) -> list[str]:
        """Compatibility view for earlier workflow consumers."""
        return self.testing_requirements


class CodeAgentInput(BaseModel):
    """Structured Requirement Agent output supplied to the Code Agent."""

    model_config = ConfigDict(extra="forbid")

    development_plan: DevelopmentPlan
    previous_test_errors: list[str] = Field(default_factory=list)
    files_to_overwrite: list[str] = Field(default_factory=list)


class CodeAgentResult(BaseModel):
    """Files generated by the Code Agent and any non-fatal warnings."""

    model_config = ConfigDict(extra="forbid")

    files_created: list[str] = Field(default_factory=list)
    files_modified: list[str] = Field(default_factory=list)
    generated_files: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)


class GeneratedFileContents(BaseModel):
    """Structured LLM response containing relative paths and source text."""

    model_config = ConfigDict(extra="forbid")

    files: dict[str, str] = Field(default_factory=dict)


class TestAgentInput(BaseModel):
    """Development plan and generated paths supplied to the Test Agent."""

    model_config = ConfigDict(extra="forbid")

    development_plan: DevelopmentPlan
    generated_files: list[str] = Field(min_length=1)
    timeout_seconds: int = Field(default=60, ge=1, le=300)


class TestAgentResult(BaseModel):
    """Test Agent report for passed/failed tests, errors, and suggestions."""

    model_config = ConfigDict(extra="forbid")

    passed: int = Field(default=0, ge=0)
    failed: int = Field(default=0, ge=0)
    errors: list[str] = Field(default_factory=list)
    suggestions: list[str] = Field(default_factory=list)
    generated_tests: list[str] = Field(default_factory=list)
    output: str | None = None
    exit_code: int | None = None


class WorkflowAttempt(BaseModel):
    """Outcome of one code-generation and optional test-execution attempt."""

    attempt_number: int = Field(ge=1)
    files: list[str] = Field(default_factory=list)
    test_output: str | None = None
    test_result: TestAgentResult | None = None
    passed: bool


class AssistantRunRequest(RequirementInput):
    """Request to run the requirement, code, and optionally test agents."""

    run_tests: bool = True


class AssistantRunResult(BaseModel):
    """Combined report from an assistant workflow execution."""

    development_plan: DevelopmentPlan
    code_result: CodeAgentResult
    test_result: TestAgentResult | None = None
    status: Literal["success", "failed"] = "success"
    attempts: list[WorkflowAttempt] = Field(default_factory=list)


class ProjectCreateRequest(BaseModel):
    """Plain-English request used to create an asynchronous project workflow."""

    model_config = ConfigDict(extra="forbid")

    request: str = Field(min_length=1, max_length=10_000)

    @field_validator("request")
    @classmethod
    def request_must_not_be_blank(cls, value: str) -> str:
        normalized = " ".join(value.split())
        if not normalized:
            raise ValueError("Request must not be blank.")
        try:
            normalized.encode("utf-8")
        except UnicodeEncodeError as exc:
            raise ValueError("Request must contain valid Unicode text.") from exc
        return normalized


class ProjectCreateResponse(BaseModel):
    """Identifier and initial state returned when a project is queued."""

    id: str
    status: Literal["queued"] = "queued"


class ProjectResponse(BaseModel):
    """Current project status and the workflow's accumulated outputs."""

    id: str
    request: str
    status: Literal["queued", "running", "completed", "failed"]
    logs: list[str] = Field(default_factory=list)
    attempts: list[WorkflowAttempt] = Field(default_factory=list)
    development_plan: DevelopmentPlan | None = None
    code_result: CodeAgentResult | None = None
    test_result: TestAgentResult | None = None
    created_at: datetime
    updated_at: datetime


class ProjectFilesResponse(BaseModel):
    """Workspace-relative generated file paths for one project."""

    project_id: str
    files: list[str] = Field(default_factory=list)
